-- Add payment detail fields to orders table
-- Run this in Supabase SQL Editor

ALTER TABLE orders
ADD COLUMN IF NOT EXISTS paid_amount DOUBLE PRECISION,
ADD COLUMN IF NOT EXISTS debt_amount DOUBLE PRECISION,
ADD COLUMN IF NOT EXISTS expected_pay_date TIMESTAMPTZ,
ADD COLUMN IF NOT EXISTS note TEXT,
ADD COLUMN IF NOT EXISTS vat_rate DOUBLE PRECISION,
ADD COLUMN IF NOT EXISTS vat_amount DOUBLE PRECISION DEFAULT 0;
